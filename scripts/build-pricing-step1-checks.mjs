// Builds the read-only checks used around applying 20261022_pricing_cost_basis.sql (step 1) to production:
//   supabase/tests/pricing_step1_snapshot.sql  every resolved price, a whole-schema fingerprint, the pricing
//                                              data fingerprint and the order/quotation/invoice sequences
//   supabase/tests/pricing_step1_sim.sql       origin/main's calls in one block that always raises
// Usage: node scripts/build-pricing-step1-checks.mjs
import { writeFileSync } from 'node:fs'
import { fingerprint, simulation, snapshot } from './pricing-sql-parts.mjs'

const query = (sql) => sql.replace(/^\s*create temporary table \S+ on commit drop as\s*/i, '').replace(/;\s*$/, '')

const claims = `select set_config('request.jwt.claim.role', 'service_role', true);
select set_config('request.jwt.claims', '{"role":"service_role"}', true);`

// Every object in public, so the before/after diff lists exactly what step 1 added or changed.
const schemaFingerprint = `
select 'fn:' || p.oid::regprocedure::text as k, md5(pg_get_functiondef(p.oid) || coalesce(p.proacl::text, '')) as v
from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.prokind in ('f', 'p')
union all
select 'rel:' || c.relname, md5(c.relkind::text || c.relrowsecurity::text || coalesce(c.relacl::text, '') ||
  coalesce((select string_agg(a.attname || ':' || format_type(a.atttypid, a.atttypmod) || ':' || a.attnotnull::text || ':' ||
    coalesce(pg_get_expr(d.adbin, d.adrelid), ''), ',' order by a.attnum)
    from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped), '') ||
  case when c.relkind = 'v' then pg_get_viewdef(c.oid) else '' end)
from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r', 'v', 'm', 'p')
union all
select 'con:' || c.conrelid::regclass::text || '.' || c.conname, md5(pg_get_constraintdef(c.oid))
from pg_constraint c join pg_namespace n on n.oid = c.connamespace where n.nspname = 'public' and c.conrelid <> 0
union all
select 'trg:' || t.tgrelid::regclass::text || '.' || t.tgname, md5(pg_get_triggerdef(t.oid))
from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and not t.tgisinternal
union all
select 'pol:' || p.tablename || '.' || p.policyname, md5(concat_ws('|', p.cmd, p.roles::text, p.qual, p.with_check))
from pg_policies p where p.schemaname = 'public'
union all
select 'idx:' || i.indexname, md5(i.indexdef) from pg_indexes i where i.schemaname = 'public'`

const snapshotSql = `-- Generated by scripts/build-pricing-step1-checks.mjs. Read-only: service-role claims are transaction-local.
${claims}
with snap as (${query(snapshot('x'))}),
fp as (${query(fingerprint('x'))}),
sch as (${schemaFingerprint})
select jsonb_build_object(
  'taken_at', now(),
  'rows', (select count(*) from snap),
  'by_kind', (select jsonb_object_agg(kind, n) from (select kind, count(*) n from snap group by kind) k),
  'prices_md5', (select md5(string_agg(concat_ws('|', kind, product_id, company_id, line_id, price), ',' order by kind, product_id, company_id, line_id, price)) from snap),
  'sequences', jsonb_build_object('order_seq', (select last_value from public.order_seq),
    'quotation_seq', (select last_value from public.quotation_seq), 'invoice_seq', (select last_value from public.invoice_seq)),
  'data_fingerprint', (select jsonb_object_agg(k, v) from fp),
  'schema_fingerprint', (select jsonb_object_agg(k, v) from sch),
  'new_columns', jsonb_build_object(
    'org_settings_default_cost_source', (select jsonb_agg(jsonb_build_object('store', to_jsonb(s) -> 'store_default_cost_source',
      'business', to_jsonb(s) -> 'business_default_cost_source', 'corporate', to_jsonb(s) -> 'corporate_default_cost_source')) from public.org_settings s),
    'product_cost_source', (select jsonb_object_agg(src, n) from
      (select coalesce(to_jsonb(pc) ->> 'cost_source', '(no column)') as src, count(*) n from public.product_costs pc group by 1) t)),
  'prices', (select jsonb_agg(jsonb_build_array(kind, product_id, company_id, line_id, price) order by kind, product_id, company_id, line_id) from snap)
) as snapshot;
`

const simSql = `-- Generated by scripts/build-pricing-step1-checks.mjs. Replays origin/main's writes and calls in one block
-- that always raises (and uses a throwaway order number), so nothing is kept and no sequence moves.
begin;
${claims}
${simulation}
do $s$ begin raise exception 'MAIN_SIM %', pg_temp.sim_main()::text; end $s$;
rollback;
`
writeFileSync('supabase/tests/pricing_step1_snapshot.sql', snapshotSql)
writeFileSync('supabase/tests/pricing_step1_sim.sql', simSql)
console.log('wrote supabase/tests/pricing_step1_snapshot.sql and supabase/tests/pricing_step1_sim.sql')
